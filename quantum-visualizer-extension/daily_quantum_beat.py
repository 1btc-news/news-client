#!/usr/bin/env python3
"""
Daily Quantum Beat Generator
Monitors quantum-related developments affecting Bitcoin security.
Produces a daily brief for aibtc.news publication.
"""
import json, urllib.request, os, sys
from datetime import datetime, timedelta

SOURCES = {
    "bitcoin_dev_list": "https://lists.linuxfoundation.org/pipermail/bitcoin-dev/",
    "arxiv_quantum": "https://arxiv.org/list/quant-ph/recent",
    "nist_pq": "https://csrc.nist.gov/projects/post-quantum-cryptography",
    "google_quantum": "https://research.google/quantum-computing/",
}

THREAT_THRESHOLDS = {
    "ECDSA_break_qubits": 500000,
    "current_public_qubits": 1000,
    "years_to_break": 5,
}

def fetch_data_json(url="https://quantum-power-map.p-d07.workers.dev/data.json"):
    try:
        req = urllib.request.Request(url)
        req.add_header('User-Agent', 'quantum-beat-generator')
        resp = urllib.request.urlopen(req, timeout=15)
        return json.loads(resp.read())
    except Exception as e:
        print(f"Error fetching data: {e}")
        return None

def compute_readiness_delta(data, prev_readiness=23):
    if not data:
        return 0, prev_readiness
    developers = data.get("developers", [])
    if not developers:
        return 0, prev_readiness
    avg_stance = sum(d.get("stance_score", 0) for d in developers) / len(developers)
    new_readiness = int(10 + (avg_stance - 1) * 17.5)
    new_readiness = max(0, min(100, new_readiness))
    delta = new_readiness - prev_readiness
    return delta, new_readiness

def generate_daily_beat(data, delta, readiness):
    today = datetime.utcnow().strftime("%B %d, %Y")
    developers = data.get("developers", [])
    total = len(developers)
    
    by_stance = {}
    for d in developers:
        label = d.get("stance_label", "Unknown")
        by_stance[label] = by_stance.get(label, 0) + 1
    
    recent = [d for d in developers if d.get("last_updated", "") == datetime.utcnow().strftime("%Y-%m-%d")]
    
    direction = "+" if delta > 0 else ("" if delta < 0 else "")
    
    lines = []
    lines.append(f"# Daily Quantum Beat - {today}")
    lines.append("")
    lines.append(f"## Bitcoin Quantum Readiness Index: {readiness}/100 {direction} ({'+' if delta >= 0 else ''}{delta})")
    lines.append("")
    lines.append("### Overview")
    no_view = by_stance.get("No known view", 0)
    advocating = by_stance.get("Advocating upgrade", 0)
    concerned = by_stance.get("Concerned, proactive", 0)
    aware = by_stance.get("Aware, no action", 0)
    dismissive = by_stance.get("Dismissive", 0)
    lines.append(f"{total} developers tracked. {advocating} advocating, {concerned} concerned, {aware} aware, {dismissive} dismissive, {no_view} no position.")
    lines.append("")
    lines.append("### Stance Distribution")
    lines.append("")
    for label, count in sorted(by_stance.items(), key=lambda x: -x[1]):
        pct = round(count / total * 100)
        lines.append(f"- **{label}**: {count} ({pct}%)")
    lines.append("")
    
    if recent:
        lines.append("### Recent Updates")
        for d in recent:
            name = d.get('name', 'Unknown')
            aff = d.get('affiliation', 'N/A')
            stance = d.get('stance_label', 'N/A')
            src = d.get('source', 'N/A')
            lines.append(f"- **{name}** ({aff}): {stance} - {src}")
        lines.append("")
    
    qubits_needed = THREAT_THRESHOLDS['ECDSA_break_qubits']
    current_qubits = THREAT_THRESHOLDS['current_public_qubits']
    years = THREAT_THRESHOLDS['years_to_break']
    status = "on track" if readiness > 50 else "sleepwalking"
    
    lines.append("### Threat Horizon")
    lines.append(f"- Physical qubits needed to break ECDSA: ~{qubits_needed:,}")
    lines.append(f"- Current state of the art: ~{current_qubits:,} physical qubits")
    lines.append(f"- Estimated time to existential risk: {years} years (conservative)")
    lines.append("")
    lines.append("### Key Signal")
    lines.append(f"37% of Bitcoin supply sits in addresses with exposed public keys. At the current Readiness Index of {readiness}/100, Bitcoin is {status} toward a quantum transition.")
    lines.append("")
    lines.append("---")
    lines.append("*Generated by Quantum Beat Generator v2.0*")
    lines.append("*Data: quantum-power-map.p-d07.workers.dev/data.json*")
    
    return "\n".join(lines)

def main():
    data = fetch_data_json()
    if not data:
        print("ERROR: Could not fetch data")
        sys.exit(1)
    
    delta, readiness = compute_readiness_delta(data)
    beat = generate_daily_beat(data, delta, readiness)
    
    output_dir = os.environ.get("OUTPUT_DIR", "/tmp")
    date_str = datetime.utcnow().strftime('%Y-%m-%d')
    output_path = os.path.join(output_dir, f"quantum-beat-{date_str}.md")
    
    with open(output_path, 'w') as f:
        f.write(beat)
    
    json_output = {
        "date": datetime.utcnow().isoformat(),
        "readiness_index": readiness,
        "readiness_delta": delta,
        "total_developers": len(data.get("developers", [])),
        "beat_markdown": beat
    }
    json_path = os.path.join(output_dir, f"quantum-beat-{date_str}.json")
    with open(json_path, 'w') as f:
        json.dump(json_output, f, indent=2)
    
    print(f"Daily beat generated: {output_path}")
    print(f"JSON version: {json_path}")
    print(f"Readiness Index: {readiness}/100 (delta: {'+' if delta >= 0 else ''}{delta})")

if __name__ == "__main__":
    main()
